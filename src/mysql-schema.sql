CREATE TABLE IF NOT EXISTS players (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    discord_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    puuid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    riot_id VARCHAR(100) NOT NULL,
    tag VARCHAR(32) NOT NULL,
    region VARCHAR(16) NOT NULL,
    summoner_level INT NOT NULL DEFAULT 0,
    tier VARCHAR(20) NOT NULL DEFAULT 'UNRANKED',
    `rank` VARCHAR(8) NOT NULL DEFAULT '',
    league_points INT NOT NULL DEFAULT 0,
    wins INT NOT NULL DEFAULT 0,
    losses INT NOT NULL DEFAULT 0,
    flex_tier VARCHAR(20) NOT NULL DEFAULT 'UNRANKED',
    flex_rank VARCHAR(8) NOT NULL DEFAULT '',
    flex_league_points INT NOT NULL DEFAULT 0,
    flex_wins INT NOT NULL DEFAULT 0,
    flex_losses INT NOT NULL DEFAULT 0,
    lane VARCHAR(20) DEFAULT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS dashboard_messages (
    channel_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    message_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    flex_message_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS voice_rooms (
    channel_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    guild_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    INDEX owner_lookup (guild_id, owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS bot_settings (
    setting_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS valorant_players (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    discord_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    puuid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    riot_id VARCHAR(100) NOT NULL,
    tag VARCHAR(32) NOT NULL,
    region VARCHAR(16) NOT NULL DEFAULT 'eu',
    account_level INT NOT NULL DEFAULT 0,
    current_tier INT NOT NULL DEFAULT 0,
    tier_name VARCHAR(32) NOT NULL DEFAULT 'Unrated',
    ranking_in_tier INT NOT NULL DEFAULT 0,
    elo INT NOT NULL DEFAULT 0,
    wins INT NOT NULL DEFAULT 0,
    number_of_games INT NOT NULL DEFAULT 0,
    agent_role VARCHAR(20) DEFAULT NULL,
    card_url VARCHAR(255) DEFAULT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS match_history (
    game VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    match_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    discord_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    win TINYINT(1) NOT NULL,
    lp_change INT DEFAULT NULL,
    played_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (game, match_id, discord_id),
    INDEX player_history (game, discord_id, played_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS weekly_baseline (
    game VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    discord_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    week_key CHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    score INT NOT NULL,
    PRIMARY KEY (game, discord_id, week_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
